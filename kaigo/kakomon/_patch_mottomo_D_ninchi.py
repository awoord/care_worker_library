def apply_updates(updates: dict[str, dict[str, str]]) -> list[str]:
    by_session: dict[int, dict[str, dict[str, str]]] = {}
    for qid, explains in updates.items():
        session = int(qid.split("-")[0])
        by_session.setdefault(session, {})[qid] = explains

    changed: list[str] = []
    for session, qmap in sorted(by_session.items()):
        path = EXPLAIN_DIR / f"explains_{session}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        for qid, explains in qmap.items():
            if qid not in data["items"]:
                raise SystemExit(f"missing {qid} in {path.name}")
            if set(explains.keys()) != {"1", "2", "3", "4", "5"}:
                raise SystemExit(f"{qid}: need keys 1-5, got {sorted(explains)}")
            for n, text in explains.items():
                if WEAK_END_RE.search(text.strip()):
                    raise SystemExit(f"weak ending left in {qid}-{n}: {text}")
            data["items"][qid]["explains"] = explains
            changed.append(qid)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    return changed


def sync_queue_explains(updated: set[str]) -> None:
    queue = json.loads(QUEUE_JSON.read_text(encoding="utf-8"))
    by_session: dict[int, dict] = {}
    for it in queue:
        qid = it["id"]
        if qid not in updated:
            continue
        session = int(qid.split("-")[0])
        if session not in by_session:
            path = EXPLAIN_DIR / f"explains_{session}.json"
            by_session[session] = json.loads(path.read_text(encoding="utf-8"))
        explains = by_session[session]["items"][qid]["explains"]
        it["explains"] = explains
        ans_raw = it["answers"]
        if isinstance(ans_raw, list):
            ans = {str(a) for a in ans_raw}
        else:
            ans = {str(ans_raw)}
        weak_ns = [
            n
            for n, e in explains.items()
            if n not in ans and WEAK_END_RE.search((e or "").strip())
        ]
        it["weak_ns"] = weak_ns
        it["weak"] = len(weak_ns)
    QUEUE_JSON.write_text(
        json.dumps(queue, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def append_review(uncertain: list[tuple[str, str]]) -> None:
    section = "## 認知症の理解・障害の理解"
    lines = [
        section,
        "",
        f"更新数: {len(UPDATES)}（対象科目: {', '.join(sorted(SUBJECTS))}）",
        "",
    ]
    if not uncertain:
        lines.append("- （なし）")
    else:
        seen: set[tuple[str, str]] = set()
        for qid, note in uncertain:
            key = (qid, note)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"- `{qid}`: {note}")
    lines.append("")
    block = "\n".join(lines)

    if REVIEW_MD.exists():
        text = REVIEW_MD.read_text(encoding="utf-8")
        if section in text:
            text = re.sub(
                rf"{re.escape(section)}\n.*?(?=\n## |\Z)",
                block.rstrip() + "\n\n",
                text,
                count=1,
                flags=re.S,
            )
            REVIEW_MD.write_text(text, encoding="utf-8")
        else:
            REVIEW_MD.write_text(text.rstrip() + "\n\n" + block, encoding="utf-8")
    else:
        header = (
            "# 「最も適切なもの」Layer D 解説・要確認リスト\n"
            "作成日: 2026-09-10\n"
            "方針: ○は設問文の手がかり＋なぜ合うか。✕はその用語・疾患・対応の正体＋この手がかりに合わない理由。"
            "設問外の症状・段階は作らない。症状名・モデル名・施策文言の教科書表記は要確認。\n\n"
        )
        REVIEW_MD.write_text(header + block, encoding="utf-8")


if __name__ == "__main__":
    expected = set(target_qids())
    missing = expected - set(UPDATES)
    extra = set(UPDATES) - expected
    if missing:
        raise SystemExit(f"missing qids in UPDATES: {sorted(missing)}")
    if extra:
        raise SystemExit(f"extra qids in UPDATES: {sorted(extra)}")

    changed = apply_updates(UPDATES)
    sync_queue_explains(set(changed))
    append_review(UNCERTAIN)

    print(f"updated {len(changed)} questions")
    for qid in sorted(
        changed, key=lambda x: (int(x.split("-")[0]), int(x.split("-")[1]))
    ):
        print(qid)
    print(f"uncertain {len(UNCERTAIN)}")
    for qid, note in UNCERTAIN:
        print(f"  {qid}: {note}")
