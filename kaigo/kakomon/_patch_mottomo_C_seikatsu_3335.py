def apply_updates(updates: dict[str, dict[str, str]]) -> list[str]:
    by_session: dict[int, dict[str, dict[str, str]]] = {}
    for qid, explains in updates.items():
        session = int(qid.split("-")[0])
        by_session.setdefault(session, {})[qid] = explains

    changed: list[str] = []
    for session, qmap in sorted(by_session.items()):
        path = EXPLAIN_DIR / f"explains_{session}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        for qid, explains in qmap.items():
            if qid not in data["items"]:
                raise SystemExit(f"missing {qid} in {path.name}")
            data["items"][qid]["explains"] = explains
            changed.append(qid)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    return changed


def sync_queue_explains(updated: set[str]) -> None:
    if not QUEUE_JSON.exists():
        return
    queue = json.loads(QUEUE_JSON.read_text(encoding="utf-8"))
    by_session: dict[int, dict] = {}
    for it in queue:
        qid = it["id"]
        if qid not in updated:
            continue
        session = int(qid.split("-")[0])
        if session not in by_session:
            path = EXPLAIN_DIR / f"explains_{session}.json"
            by_session[session] = json.loads(path.read_text(encoding="utf-8"))
        explains = by_session[session]["items"][qid]["explains"]
        it["explains"] = explains
        ans_raw = it["answers"]
        if isinstance(ans_raw, list):
            ans = {str(a) for a in ans_raw}
        else:
            ans = {str(ans_raw)}
        weak_ns = [
            n
            for n, e in explains.items()
            if n not in ans and WEAK_END_RE.search((e or "").strip())
        ]
        it["weak_ns"] = weak_ns
        it["weak"] = len(weak_ns)
    QUEUE_JSON.write_text(
        json.dumps(queue, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def append_review(uncertain: list[tuple[str, str]]) -> None:
    section = "## 生活支援技術（第33〜35回）"
    lines = [
        section,
        "",
        f"更新数: {len(UPDATES)}（対象科目: {', '.join(SUBJECTS)}／回: {ROUNDS[0]}–{ROUNDS[-1]}）",
        "",
    ]
    if uncertain:
        for qid, note in uncertain:
            lines.append(f"- `{qid}`: {note}")
    else:
        lines.append("- （該当事項なし）")
    lines.append("")
    block = "\n".join(lines)

    if REVIEW_MD.exists():
        text = REVIEW_MD.read_text(encoding="utf-8")
        if section in text:
            text = re.sub(
                rf"{re.escape(section)}\n.*?(?=\n## |\Z)",
                block.rstrip() + "\n\n",
                text,
                count=1,
                flags=re.S,
            )
            REVIEW_MD.write_text(text, encoding="utf-8")
        else:
            REVIEW_MD.write_text(text.rstrip() + "\n\n" + block, encoding="utf-8")
    else:
        header = (
            "# 「最も適切なもの」Layer C 解説・要確認リスト\n"
            "作成日: 2026-09-10\n"
            "方針: ○は設問文の手がかり＋なぜその手技・用具が合うか。"
            "✕はその方法・用具の正体＋この条件に合わない理由。"
            "設問外の数値は作らず、図依存・教科書細部は要確認。\n\n"
        )
        REVIEW_MD.write_text(header + block, encoding="utf-8")


def _verify_answers_unchanged(updated: list[str]) -> None:
    queue = json.loads(QUEUE_JSON.read_text(encoding="utf-8"))
    q_ans = {it["id"]: str(it["answers"]) for it in queue}

    for qid in updated:
        sess, num = qid.split("-")
        path = EXPLAIN_DIR / f"explains_{sess}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        item = data["items"][qid]
        explains = item["explains"]
        if set(explains.keys()) != {"1", "2", "3", "4", "5"}:
            raise SystemExit(f"{qid}: explains keys incomplete: {sorted(explains)}")

        csv_ans = None
        with (ROOT / f"answers_{sess}.csv").open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if str(row["session"]) == sess and str(int(row["number"])) == str(
                    int(num)
                ):
                    csv_ans = str(row["answer"])
                    break
        if csv_ans is None:
            raise SystemExit(f"{qid}: missing csv answer")
        if q_ans.get(qid) != csv_ans:
            raise SystemExit(f"{qid}: queue ans {q_ans.get(qid)} != csv {csv_ans}")

        # correct choice explain should not be empty
        if not (explains.get(csv_ans) or "").strip():
            raise SystemExit(f"{qid}: empty correct explain for {csv_ans}")


def _check_scope() -> None:
    queue = json.loads(QUEUE_JSON.read_text(encoding="utf-8"))
    expected = {
        it["id"]
        for it in queue
        if it["subject"] == "生活支援技術" and it["round"] in ROUNDS
    }
    got = set(UPDATES)
    if got != expected:
        missing = sorted(expected - got)
        extra = sorted(got - expected)
        raise SystemExit(f"scope mismatch missing={missing} extra={extra}")


