def _verify_answers_unchanged(updated: list[str]) -> None:
    import csv

    for qid in updated:
        sess, num = qid.split("-")
        path = EXPLAIN_DIR / f"explains_{sess}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        item = data["items"][qid]
        explains = item["explains"]
        if set(explains.keys()) != {"1", "2", "3", "4", "5"}:
            raise SystemExit(f"{qid}: explains keys incomplete: {sorted(explains)}")
        csv_ans = None
        with (ROOT / f"answers_{sess}.csv").open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if str(row["session"]) == sess and str(int(row["number"])) == str(
                    int(num)
                ):
                    csv_ans = str(row["answer"])
                    break
        stored = item.get("answer") or item.get("answers")
        if stored is not None and str(stored) != csv_ans:
            raise SystemExit(f"{qid}: answer field drifted {stored} vs csv {csv_ans}")


def _check_scope() -> None:
    queue = json.loads(QUEUE_JSON.read_text(encoding="utf-8"))
    expected = {
        it["id"]
        for it in queue
        if it.get("subject") == SUBJECT and it.get("round") in ROUNDS
    }
    got = set(UPDATES)
    if got != expected:
        missing = sorted(expected - got)
        extra = sorted(got - expected)
        raise SystemExit(f"scope mismatch missing={missing} extra={extra}")


