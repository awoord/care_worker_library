def apply_updates(updates: dict[str, dict[str, str]]) -> list[str]:
    by_session: dict[int, dict[str, dict[str, str]]] = {}
    for qid, explains in updates.items():
        session = int(qid.split("-")[0])
        by_session.setdefault(session, {})[qid] = explains

    changed: list[str] = []
    for session, qmap in sorted(by_session.items()):
        path = EXPLAIN_DIR / f"explains_{session}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        for qid, explains in qmap.items():
            if qid not in data["items"]:
                raise SystemExit(f"missing {qid} in {path.name}")
            if set(explains.keys()) != {"1", "2", "3", "4", "5"}:
                raise SystemExit(f"bad keys for {qid}: {sorted(explains)}")
            data["items"][qid]["explains"] = explains
            changed.append(qid)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    return changed


def _replace_or_append_section(text: str, section: str, body_lines: list[str]) -> str:
    block = section + "\n\n" + "\n".join(body_lines) + "\n"
    if section in text:
        start = text.index(section)
        rest = text[start + len(section) :]
        next_h = rest.find("\n## ")
        if next_h == -1:
            return text[:start] + block
        return text[:start] + block + rest[next_h + 1 :]
    sep = "" if text.endswith("\n") else "\n"
    return text + sep + "\n" + block


def append_review(uncertain: list[tuple[str, str]]) -> None:
    by_subj: dict[str, list[tuple[str, str]]] = {s: [] for s in SECTION_ORDER}
    for qid, reason in uncertain:
        subj = SUBJECT_BY_QID.get(qid, "その他")
        by_subj.setdefault(subj, []).append((qid, reason))

    if REVIEW_MD.exists():
        text = REVIEW_MD.read_text(encoding="utf-8")
    else:
        text = "# 「適切なもの」解説・要確認リスト\n"

    for subj in SECTION_ORDER:
        items = by_subj.get(subj) or []
        if not items:
            continue
        section = f"## {subj}"
        body = [f"- `{qid}`: {reason}" for qid, reason in items]
        text = _replace_or_append_section(text, section, body)

    if not text.endswith("\n"):
        text += "\n"
    REVIEW_MD.write_text(text, encoding="utf-8")


