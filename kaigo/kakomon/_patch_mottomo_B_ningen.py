def apply_updates(updates: dict[str, dict[str, str]]) -> list[str]:
    by_session: dict[int, dict[str, dict[str, str]]] = {}
    for qid, explains in updates.items():
        session = int(qid.split("-")[0])
        by_session.setdefault(session, {})[qid] = explains

    changed: list[str] = []
    for session, qmap in sorted(by_session.items()):
        path = EXPLAIN_DIR / f"explains_{session}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        for qid, explains in qmap.items():
            if qid not in data["items"]:
                raise SystemExit(f"missing {qid} in {path.name}")
            # never change correct answer — only explains
            data["items"][qid]["explains"] = explains
            changed.append(qid)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    return changed


def append_review(uncertain: list[tuple[str, str]]) -> None:
    section = "## 人間関係とコミュニケーション"
    lines = [
        section,
        "",
        f"更新数: {len(UPDATES)}（対象科目: {', '.join(SUBJECTS)}）",
        "",
    ]
    if uncertain:
        for qid, note in uncertain:
            lines.append(f"- `{qid}`: {note}")
    else:
        lines.append("- （該当事項なし）")
    lines.append("")
    block = "\n".join(lines)

    if REVIEW_MD.exists():
        text = REVIEW_MD.read_text(encoding="utf-8")
        if section in text:
            text = re.sub(
                rf"{re.escape(section)}\n.*?(?=\n## |\Z)",
                block.rstrip() + "\n\n",
                text,
                count=1,
                flags=re.S,
            )
            REVIEW_MD.write_text(text, encoding="utf-8")
        else:
            REVIEW_MD.write_text(text.rstrip() + "\n\n" + block, encoding="utf-8")
    else:
        header = (
            "# 「最も適切なもの」Layer B 解説・要確認リスト\n"
            "作成日: 2026-09-10\n"
            "方針: ○は設問文の手がかり＋なぜその対応・姿勢が合うか。"
            "✕はその対応の内容＋この場面／問いで合わない理由。"
            "設問外の断定は避け、心理ラベルや分類境界は要確認。\n\n"
        )
        REVIEW_MD.write_text(header + block, encoding="utf-8")


if __name__ == "__main__":
    # sanity: answers in queue must match CSV; explains keys cover 1-5
    import csv

    queue = json.loads((ROOT / "explains_mottomo_B_queue.json").read_text(encoding="utf-8"))
    qmap = {x["id"]: x for x in queue if x.get("subject") == "人間関係とコミュニケーション"}
    answers: dict[str, str] = {}
    for p in ROOT.glob("answers_*.csv"):
        with p.open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                answers[f"{row['session']}-{row['number']}"] = row["answer"]

    for qid, explains in UPDATES.items():
        if qid not in qmap:
            raise SystemExit(f"qid not in queue subject filter: {qid}")
        ans = str(qmap[qid]["answers"])
        csv_ans = answers.get(qid)
        if csv_ans is not None and str(csv_ans) != ans:
            raise SystemExit(f"answer mismatch {qid}: queue={ans} csv={csv_ans}")
        if set(explains.keys()) != {"1", "2", "3", "4", "5"}:
            raise SystemExit(f"need keys 1-5 for {qid}: {sorted(explains)}")
        if ans not in explains:
            raise SystemExit(f"correct answer key missing for {qid}")

    changed = apply_updates(UPDATES)
    append_review(UNCERTAIN)
    print(f"updated {len(changed)} questions")
    for qid in changed:
        print(qid)
    print(f"uncertain {len(UNCERTAIN)}")
    for qid, note in UNCERTAIN:
        print(f"  {qid}: {note}")
